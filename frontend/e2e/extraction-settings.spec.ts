import { expect, test } from '@playwright/test'

test('independent extraction settings persist without changing the chat provider', async ({ page, request }) => {
  const base = 'http://127.0.0.1:18000/api'
  const before = await (await request.get(`${base}/settings/provider`)).json()
  await page.goto('/')
  await page.getByRole('navigation').getByRole('button', { name: 'Einstellungen', exact: true }).click()
  await page.getByText('Erweitert: Erkennung von Erinnerungen und Weltänderungen', { exact: true }).click()
  const form = page.getByRole('form', { name: 'Ereignisextraktion' })
  await form.getByLabel('Anbieterprofil der Extraktion').selectOption('lmstudio')
  await form.getByLabel('Reasoning bei der Extraktion').selectOption('off')
  await form.getByLabel('Extraktionsmodell (leer = Chatmodell)').fill('qwen/qwen3.5-9b')
  await form.getByLabel('Extraktion: Ausgabetokens').fill('8192')
  await form.getByLabel('Extraktion: Zeitlimit (Sekunden)').fill('600')
  await form.getByLabel('Höchstens eine gezielte automatische Wiederholung erlauben').uncheck()
  await form.getByRole('button', { name: 'Extraktionseinstellungen speichern' }).click()
  await expect(form.getByRole('status')).toContainText('Extraktionseinstellungen gespeichert')
  const settings = await (await request.get(`${base}/settings/extraction`)).json()
  expect(settings.provider_profile).toBe('lmstudio')
  expect(settings.reasoning_mode).toBe('off')
  expect(settings.max_output_tokens).toBe(8192)
  expect(settings.timeout_seconds).toBe(600)
  expect(settings.auto_retry).toBe(false)
  expect(await (await request.get(`${base}/settings/provider`)).json()).toEqual(before)
  await page.getByText('Erweitert: Verbindung manuell bearbeiten', { exact: true }).click()
  await page.getByText('Erweiterte Modelleinstellungen', { exact: true }).click()
  await page.getByLabel('Modellname', { exact: true }).fill('test-chat-model')
  await page.getByLabel('Reasoning-Profil des Chats').selectOption('lmstudio')
  await page.getByLabel('Reasoning im Chat', { exact: true }).selectOption('off')
  await page.getByRole('button', { name: 'Verbindung speichern', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Die Verbindung wird' }))
    .toContainText('Einstellungen gespeichert')
  const chat = await (await request.get(`${base}/settings/provider`)).json()
  expect(chat.reasoning_profile).toBe('lmstudio')
  expect(chat.reasoning_mode).toBe('off')
  expect((await (await request.get(`${base}/settings/extraction`)).json()).max_output_tokens).toBe(8192)
  await page.reload()
  await page.getByRole('navigation').getByRole('button', { name: 'Einstellungen', exact: true }).click()
  await page.getByText('Erweitert: Erkennung von Erinnerungen und Weltänderungen', { exact: true }).click()
  await expect(form.getByLabel('Extraktion: Ausgabetokens')).toHaveValue('8192')
  await expect(form.getByLabel('Reasoning bei der Extraktion')).toHaveValue('off')
  await expect(form.getByLabel('Höchstens eine gezielte automatische Wiederholung erlauben')).not.toBeChecked()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await request.put(`${base}/settings/extraction`, { data: {} })
})
