import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

async function navigate(page: Page, name: string) {
  await page.getByRole('navigation').getByRole('button', { name, exact: true }).click()
}
async function save(page: Page) {
  await page.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Schließen', exact: true })).toHaveCount(0)
  await expect(page.getByRole('alert')).toHaveCount(0)
}

test('Eldoria: graphical editors, private knowledge, streaming and persistent continuation', async ({ page, request }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Neue Welt', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill('Eldoria')
  await page.getByLabel('Öffentliche Weltbeschreibung').fill('Eine fantastische Welt.')
  await save(page)
  await page.getByRole('button', { name: 'Eldoria öffnen' }).click()

  for (const name of ['Shadowfang', 'Glade']) {
    await page.getByRole('button', { name: 'Neuer Ort', exact: true }).click()
    await page.getByLabel('Name', { exact: true }).fill(name)
    await page.getByLabel('Typ', { exact: true }).fill('Region')
    if (name === 'Glade') {
      await page.getByRole('button', { name: 'Feld hinzufügen' }).click()
      await page.getByLabel('Feldname').fill('Magische Instabilitaet')
      await page.getByLabel('Feldtyp').selectOption('number')
      await page.getByLabel('Minimum (optional)').fill('0')
      await page.getByLabel('Maximum (optional)').fill('100')
      await page.getByLabel('Wert', { exact: true }).fill('42')
    }
    await save(page)
  }
  await page.getByRole('button', { name: 'Glade Region', exact: true }).click()
  await expect(page.getByLabel('Wert', { exact: true })).toHaveValue('42')
  await page.getByRole('button', { name: 'Schließen', exact: true }).click()

  await navigate(page, 'Charaktere')
  for (const [name, location] of [['Lumia', 'Glade'], ['Power', 'Shadowfang']]) {
    await page.getByRole('button', { name: 'Neuer Charakter', exact: true }).click()
    await page.getByLabel('Name', { exact: true }).fill(name!)
    await page.getByRole('tab', { name: 'Persönlichkeit & Hintergrund' }).click()
    await page.getByLabel('Persönlichkeit', { exact: true }).fill('Neugierig und freundlich')
    if (name === 'Power') await page.getByLabel('Inventar').fill('Geheimer Kristall')
    await page.getByRole('tab', { name: 'Zustand & Ort' }).click()
    await page.getByLabel('Aufenthaltsstatus').selectOption('present')
    await page.getByLabel('Aktueller Ort', { exact: true }).selectOption({ label: location! })
    await save(page)
  }
  await navigate(page, 'Beziehungen')
  await page.getByRole('button', { name: 'Neue Beziehung', exact: true }).click()
  await page.getByLabel('Von Charakter').selectOption({ label: 'Lumia' })
  await page.getByLabel('Zu Charakter').selectOption({ label: 'Power' })
  await page.getByLabel('Beziehungstyp').fill('Bekanntschaft')
  await page.getByRole('button', { name: 'Feld hinzufügen' }).click()
  await page.getByLabel('Feldname').fill('Vertrauen')
  await page.getByLabel('Feldtyp').selectOption('number')
  await page.getByLabel('Wert', { exact: true }).fill('90')
  await save(page)
  await expect(page.getByRole('cell', { name: 'Bekanntschaft' })).toBeVisible()

  await navigate(page, 'Wissen & Erinnerungen')
  await page.getByRole('button', { name: 'Neuer Wissenseintrag' }).click()
  await page.getByLabel('Wissensart').selectOption('fact')
  await page.getByLabel('Inhalt', { exact: true }).fill('Power besitzt einen geheimen Kristall.')
  await save(page)
  await page.getByRole('button', { name: 'Neuer Wissenseintrag' }).click()
  await page.getByLabel('Wissensart').selectOption('secret')
  await page.getByLabel('Bekannt für').selectOption({ label: 'Power' })
  await page.getByLabel('Inhalt', { exact: true }).fill('Ich besitze einen geheimen Kristall.')
  await save(page)

  await navigate(page, 'Einstellungen')
  await page.getByLabel('Base-URL').fill('http://127.0.0.1:18090/v1')
  await page.getByLabel('Modellname').fill('TEST-ONLY')
  await page.getByRole('button', { name: 'Verbindung speichern' }).click()
  await expect(page.getByRole('status')).toContainText('Einstellungen gespeichert')

  await navigate(page, 'Ereignisse')
  await page.getByText('Ereigniserkennung und Freigaben', { exact: true }).click()
  await page.getByLabel('Ereignisse nach Gesprächen erkennen').check()
  await expect(page.getByLabel('Ereignisse nach Gesprächen erkennen')).toBeEnabled()
  await navigate(page, 'Chats')
  await page.getByLabel('Charakter', { exact: true }).selectOption({ label: 'Lumia' })
  await page.getByRole('button', { name: 'Neues Gespräch', exact: true }).click()
  await page.getByLabel('Deine Nachricht').fill('Hallo Lumia.')
  await page.getByRole('button', { name: 'Senden', exact: true }).click()
  await expect(page.getByLabel('Deine Nachricht')).toBeEnabled()
  const captured = await (await request.get('http://127.0.0.1:18090/requests')).json()
  expect(JSON.stringify(captured[0].messages)).not.toContain('Kristall')
  expect(JSON.stringify(captured[0].messages)).not.toContain('Shadowfang')
  await expect(page.locator('.messages')).toContainText('Von einem Kristall weiss ich nichts.')

  await page.getByLabel('Deine Nachricht').fill('Power hat einen Kristall gefunden.')
  await page.getByRole('button', { name: 'Senden', exact: true }).click()
  await expect(page.getByLabel('Deine Nachricht')).toBeEnabled()
  await expect(page.locator('.messages')).toContainText('Das weiss ich nur aus deiner Aussage.')
  await navigate(page, 'Wissen & Erinnerungen')
  await page.getByLabel('Wissensstand anzeigen:').selectOption({ label: 'Lumia' })
  await expect(page.locator('article')).toHaveCount(1)
  await expect(page.locator('article')).toContainText('Benutzeraussage')
  await expect(page.locator('article')).toContainText('Power hat einen Kristall gefunden.')
  await page.getByLabel('Wissensstand anzeigen:').selectOption({ label: 'Power' })
  await expect(page.locator('article')).toHaveCount(1)
  await expect(page.locator('article')).not.toContainText('Benutzeraussage')
  await page.getByLabel('Wissensstand anzeigen:').selectOption('world')
  await expect(page.locator('article')).toContainText('Power besitzt einen geheimen Kristall.')

  await page.reload()
  await page.getByRole('button', { name: 'Eldoria öffnen' }).click()
  await navigate(page, 'Chats')
  await page.getByLabel('Charakter', { exact: true }).selectOption({ label: 'Lumia' })
  await page.getByRole('button', { name: 'Neues Gespräch', exact: true }).click()
  await page.getByLabel('Deine Nachricht').fill('Was weisst du ueber Power?')
  await page.getByRole('button', { name: 'Senden', exact: true }).click()
  await expect(page.getByLabel('Deine Nachricht')).toBeEnabled()
  await expect(page.locator('.messages')).toContainText('Das weiss ich nur aus deiner Aussage.')
  const later = await (await request.get('http://127.0.0.1:18090/requests')).json()
  expect(JSON.stringify(later.at(-1).messages)).toContain('Power hat einen Kristall gefunden.')
  expect(JSON.stringify(later.at(-1).messages)).not.toContain('Power besitzt einen geheimen Kristall.')

  await page.getByRole('button', { name: 'Erneut antworten' }).click()
  await expect(page.getByLabel('Deine Nachricht')).toBeEnabled()
  await expect(page.locator('.message')).toHaveCount(2)
  await page.getByRole('button', { name: 'Nachricht bearbeiten' }).click()
  await page.locator('.message textarea').fill('Was weisst du ueber Glade?')
  await page.getByRole('button', { name: 'Änderung speichern' }).click()
  await page.getByRole('button', { name: 'Bestätigen', exact: true }).click()
  await expect(page.locator('.message')).toHaveCount(1)
  await expect(page.locator('.messages')).toContainText('Was weisst du ueber Glade?')

  await page.setViewportSize({ width: 390, height: 844 })
  await navigate(page, 'Meine Welten')
  await expect(page.getByRole('button', { name: 'Neue Welt', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: 'test-results/mobile-worlds.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: 'test-results/desktop-worlds.png', fullPage: true })
  expect(errors).toEqual([])
})
